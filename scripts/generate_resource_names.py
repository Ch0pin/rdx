#!/usr/bin/env python3
"""Generate framework attribute identities from an SDK public-final.xml snapshot."""
import argparse
import hashlib
import re
from pathlib import Path
import xml.etree.ElementTree as ET


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    source = args.source.read_bytes()
    names = {}
    for node in ET.fromstring(source).findall("public"):
        if node.get("type") != "attr":
            continue
        resource_id = int(node.attrib["id"], 16)
        name = node.attrib["name"]
        if resource_id >> 16 != 0x0101 or not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", name):
            raise ValueError("Invalid framework attribute declaration")
        if resource_id in names:
            raise ValueError("Duplicate framework attribute ID")
        names[resource_id] = name
    if not names:
        raise ValueError("No framework attributes")
    lines = [
        "// Generated by scripts/generate_resource_names.py; do not edit manually.",
        "// Android SDK 36 data/res/values/public-final.xml; AOSP resource identity facts.",
        f"// Source SHA-256: {hashlib.sha256(source).hexdigest()}",
        "// Framework IDs are stable; unknown IDs are never assigned guessed names.",
        "pub(super) fn attribute(id: u32) -> Option<&'static str> {",
        "    NAMES",
        "        .binary_search_by_key(&id, |&(key, _)| key)",
        "        .ok()",
        "        .map(|index| NAMES[index].1)",
        "}",
        "const NAMES: &[(u32, &str)] = &[",
    ]
    lines.extend(f'    (0x{key:08x}, "{value}"),' for key, value in sorted(names.items()))
    lines.append("];")
    args.destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(names)} framework attribute identities")


if __name__ == "__main__":
    main()
